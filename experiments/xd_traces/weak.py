#!/usr/bin/env python3
"""Weak-order structure of V_N inside S_N, in two encodings.

 enc 'seq' : w = the sequence a (a_k = panel placed at step k).  Covers of the right weak
             order = exchange of two ADJACENT STEPS.
 enc 'time': w = the time word t (t_m = step at which panel m is placed) = a^{-1}.  Covers =
             exchange of the times of two ADJACENT PANELS m, m+1.

For each: number of connected components of V_N in the cover graph, order-convexity,
closure under join / meet, the Moebius number mu(0^,1^) of the induced subposet with a
bottom and top added, whether V_N is a union of classes of a non-trivial lattice
congruence (N <= 6: polygon forcing closure), number of maximal intervals.
"""
import sys, itertools
from collections import defaultdict
from brute import gen

def inv_mask(w, N, idx):
    m = 0
    for i in range(N):
        for j in range(i + 1, N):
            if w[i] > w[j]: m |= 1 << idx[(w[j], w[i])]
    return m

def closure(mask, N, idx, pairs):
    """transitive closure of a set of pairs (a<b meaning b before a) -> inversion set"""
    rel = [[False] * (N + 1) for _ in range(N + 1)]
    for k, (a, b) in enumerate(pairs):
        if mask >> k & 1: rel[a][b] = True
    changed = True
    while changed:
        changed = False
        for a in range(1, N + 1):
            for b in range(a + 1, N + 1):
                if rel[a][b]: continue
                for c in range(a + 1, b):
                    if rel[a][c] and rel[c][b]:
                        rel[a][b] = True; changed = True; break
    m = 0
    for k, (a, b) in enumerate(pairs):
        if rel[a][b]: m |= 1 << k
    return m

def analyse(N, enc, V):
    pairs = [(a, b) for a in range(1, N + 1) for b in range(a + 1, N + 1)]
    idx = {p: k for k, p in enumerate(pairs)}
    full = (1 << len(pairs)) - 1
    if enc == 'time':
        W = []
        for a in V:
            t = [0] * N
            for k, m in enumerate(a): t[m - 1] = k + 1
            W.append(tuple(t))
    else:
        W = list(V)
    Wset = set(W)
    invs = {w: inv_mask(w, N, idx) for w in W}
    invset = set(invs.values())
    # components in the cover graph
    par = {w: w for w in W}
    def find(x):
        while par[x] != x:
            par[x] = par[par[x]]; x = par[x]
        return x
    edges = 0
    for w in W:
        for p in range(N - 1):
            v = list(w); v[p], v[p + 1] = v[p + 1], v[p]; v = tuple(v)
            if v in Wset:
                edges += 1
                a, b = find(w), find(v)
                if a != b: par[a] = b
    comps = defaultdict(list)
    for w in W: comps[find(w)].append(w)
    ncomp = len(comps)
    # is every component an interval of S_N ?  (min/max by inversions, count the interval)
    res = f"  [{enc}] components={ncomp} internal_edges={edges // 2}"
    # convexity
    if N <= 8:
        vm = list(invs.values())
        nonconvex = 0
        for w in itertools.permutations(range(1, N + 1)):
            if w in Wset: continue
            m = inv_mask(w, N, idx)
            lo = any((u & m) == u for u in vm)
            if not lo: continue
            hi = any((u & m) == m for u in vm)
            if hi: nonconvex += 1
        res += f" convex={'yes' if nonconvex == 0 else 'no'}(holes={nonconvex})"
    # join / meet closure
    if N <= 7:
        vm = sorted(invset); nj = nm = tot = 0
        for i in range(len(vm)):
            for j in range(i + 1, len(vm)):
                tot += 1
                jn = closure(vm[i] | vm[j], N, idx, pairs)
                mt = full ^ closure((full ^ vm[i]) | (full ^ vm[j]), N, idx, pairs)
                if jn in invset: nj += 1
                if mt in invset: nm += 1
        res += f" join_closed={nj}/{tot} meet_closed={nm}/{tot}"
    # Moebius number of V_N with 0^ and 1^ adjoined
    if len(W) <= 5000:
        ws = sorted(W, key=lambda w: bin(invs[w]).count('1'))
        n = len(ws); im = [invs[w] for w in ws]
        mu = [0] * n   # mu(0^, w)
        total = 1      # mu(0^,0^)
        for i in range(n):
            s = 1
            mi = im[i]
            for j in range(i):
                if (im[j] & mi) == im[j]: s += mu[j]
            mu[i] = -s; total += mu[i]
        res += f" mu(0^,1^)={-total}"
    # maximal intervals contained in V_N
    if len(W) <= 1200:
        vm = sorted(invset, key=lambda m: bin(m).count('1'))
        # interval [u,v] in V_N iff every permutation between is in V_N; test via counting
        # elements of V_N in between vs size of the S_N interval (computed by brute force
        # only for N<=7)
        pass
    return res, comps, invs

def congruence_test(N, V):
    """seq encoding, N<=6.  Polygon forcing in the weak order of S_N.  Is V_N a union of
    classes of the congruence generated by contracting all cover edges inside V_N?  And is
    there ANY single edge whose forcing closure avoids the boundary of V_N?"""
    perms = list(itertools.permutations(range(1, N + 1)))
    Vs = set(V)
    def edge(u, p):   # cover edge: swap positions p,p+1 ; normalised (lower, p)
        v = list(u); v[p], v[p + 1] = v[p + 1], v[p]; v = tuple(v)
        return (u, p) if u[p] < u[p + 1] else (v, p)
    def other(u, p):
        v = list(u); v[p], v[p + 1] = v[p + 1], v[p]; return tuple(v)
    # polygons: bottom x, with ascents at p and q.
    force = defaultdict(set)
    for x in perms:
        asc = [p for p in range(N - 1) if x[p] < x[p + 1]]
        for i in range(len(asc)):
            for j in range(i + 1, len(asc)):
                p, q = asc[i], asc[j]
                if q - p >= 2:  # square: x, xp, xq, xpq
                    xp, xq = other(x, p), other(x, q)
                    b1, b2 = (x, p), (x, q); t1, t2 = (xq, p), (xp, q)   # t1 opposite...
                    # bottom edge (x,p) forces opposite top edge: from xq up by p -> (xq,p)
                    force[b1].add(t1); force[t1].add(b1)
                    force[b2].add(t2); force[t2].add(b2)
                else:          # hexagon on positions p,p+1,p+2
                    # chains: x -p-> a1 -q-> a2 -p-> y ; x -q-> b1 -p-> b2 -q-> y
                    a1 = other(x, p); a2 = other(a1, q); b1 = other(x, q); b2 = other(b1, p)
                    eb1, eb2 = (x, p), (x, q)
                    et1, et2 = (a2, p), (b2, q)      # top edges a2->y (swap p), b2->y (swap q)
                    es1, es2 = (a1, q), (b1, p)      # side edges
                    # bottom (x,p) is opposite to top edge of the other chain (b2,q)
                    for b, t in ((eb1, et2), (eb2, et1)):
                        force[b].add(t); force[t].add(b)
                        force[b].add(es1); force[b].add(es2)
                        force[t].add(es1); force[t].add(es2)
    def close(seed):
        seen = set(seed); st = list(seed)
        while st:
            e = st.pop()
            for f in force[e]:
                if f not in seen: seen.add(f); st.append(f)
        return seen
    def crosses(E):
        for (u, p) in E:
            v = other(u, p)
            if (u in Vs) != (v in Vs): return True
        return False
    inner = set()
    for u in V:
        for p in range(N - 1):
            v = other(u, p)
            if v in Vs: inner.add(edge(u, p))
    C = close(inner)
    r1 = not crosses(C)
    # any single edge?
    good = 0; alledges = set(edge(u, p) for u in perms for p in range(N - 1))
    done = set()
    for e in alledges:
        if e in done: continue
        C1 = close([e])
        if not crosses(C1):
            good += 1
    return (f"  [seq] congruence generated by all swaps inside V_N: contracted edges="
            f"{len(C)}/{len(alledges)}, V_N union of its classes: {r1}; "
            f"single edges whose forcing closure does not cross the boundary of V_N: {good}/{len(alledges)}")

if __name__ == "__main__":
    maxN = int(sys.argv[1]) if len(sys.argv) > 1 else 8
    for N in range(2, maxN + 1):
        V = gen(N)
        print(f"N={N} |V|={len(V)}")
        for enc in ('seq', 'time'):
            res, comps, invs = analyse(N, enc, V)
            sizes = sorted(len(c) for c in comps.values())
            print(res, "| component sizes: min", sizes[0], "max", sizes[-1],
                  "singletons", sum(1 for s in sizes if s == 1))
        if N <= 6: print(congruence_test(N, V))
        sys.stdout.flush()
