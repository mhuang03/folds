# final.py M > ../../Folds/Live3q.lean : core.lean (definitions and soundness) + the kernel
# certificates for 31 <= N <= M (mkq.py) + the final theorems.
import sys, io
import mkq

M = int(sys.argv[1])
chunk = int(sys.argv[2]) if len(sys.argv) > 2 else 40
core = open('core.lean').read()
end = 'end Live3q\nend Folds\n'
assert core.endswith(end)
out = sys.stdout
out.write(core[:-len(end)])
out.write('\n/-! ## Certificates for `31 ≤ N ≤ %d` (generated by `experiments/live3q/mkq.py`)\n\n'
          'Checked sequentially (`Elab.async false`) to keep the memory low. -/\n\n' % M)
out.write('set_option Elab.async false\n\n')
for N in range(31, M + 1):
    mkq.gen(N, 3, chunk, out)
out.write('''/-! ## The 3-prefix iff for `N ≤ %(M)d`, and for all `N` modulo the residual -/

/-- **`Good3 N` for every `N ≤ %(M)d`, `N ≠ 7`.** -/
theorem good3_le_%(M)d : ∀ N, N ≤ %(M)d → N ≠ 7 → Good3 N := by
  intro N
  induction N using Nat.strong_induction_on with
  | _ N ih =>
    intro hN h7
    by_cases h30 : N ≤ 30
    · exact good3_le_30 h30 h7
    have IH : ∀ q, q < N → q ≠ 7 → Good3 q := fun q hq h7' => ih q hq (by omega) h7'
    have h31 : 31 ≤ N := by omega
    interval_cases N
    exacts [%(cases)s]

/-- **The 3-prefix analogue of Conjecture C for every `N ≤ %(M)d`, `N ≠ 7`**: a valid 3-prefix
is live iff its set is not one of the dead 3-sets `Dead3`. -/
theorem extends3_iff_le_%(M)d {N x y z : Nat} (hN : N ≤ %(M)d) (h7 : N ≠ 7)
    (hx : 1 ≤ x ∧ x ≤ N) (hy : 1 ≤ y ∧ y ≤ N) (hz : 1 ≤ z ∧ z ≤ N) (hxy : x ≠ y)
    (hxz : x ≠ z) (hyz : y ≠ z) (hv : SemiSymmetric N [x, y, z]) :
    Extends N [x, y, z] ↔ ¬ Dead3 N {x, y, z} :=
  extends3_iff_of_good3 (good3_le_%(M)d N hN h7) hx hy hz hxy hxz hyz hv

/-- **The 3-prefix analogue of Conjecture C for all `N ≠ 7`, modulo the residual**: if for
every `N > %(M)d` the valid non-dead triples not settled by `Covered3S` (Theorem G in closed
form, Theorem G after at most two explicit steps, a transfer through a copy from a smaller
strip, or the same for the mirror image) are co-reachable, then for every `N ≠ 7` a valid
3-prefix is live iff its set is not dead. -/
theorem extends3_iff_of_residual (hres : ∀ N, %(M)d < N → Residual3 N) {N x y z : Nat}
    (h7 : N ≠ 7) (hx : 1 ≤ x ∧ x ≤ N) (hy : 1 ≤ y ∧ y ≤ N) (hz : 1 ≤ z ∧ z ≤ N)
    (hxy : x ≠ y) (hxz : x ≠ z) (hyz : y ≠ z) (hv : SemiSymmetric N [x, y, z]) :
    Extends N [x, y, z] ↔ ¬ Dead3 N {x, y, z} :=
  extends3_iff_of_good3 (good3_of_residual good3_le_%(M)d hres N h7) hx hy hz hxy hxz hyz hv

end Live3q
end Folds
''' % {'M': M, 'cases': ', '.join('good3_of_cov IH cov_%d' % N for N in range(31, M + 1))})
