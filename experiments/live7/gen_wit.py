"""gen_wit.py: witness orderings for the hard-core pairs (experiments/live6/core520.txt) with
N <= NMAX, and the Lean block of Folds/Live7.lean between the markers
'-- BEGIN WITNESSES' and '-- END WITNESSES'.  Orderings are cached in witnesses.txt
(one line 'N u v x1,x2,...': an ordering of [N] minus {u, v} from scratch)."""
import ast
import os
import sys
from mkwit import witness, semi_ok

HERE = os.path.dirname(os.path.abspath(__file__))
NMAX = int(sys.argv[1]) if len(sys.argv) > 1 else 128


def core_pairs():
    out = []
    for line in open(os.path.join(HERE, '..', 'live6', 'core520.txt')):
        N, k, rest = line.split(' ', 2)
        for (u, v) in ast.literal_eval(rest.strip()):
            out.append((int(N), u, v))
    # pairs that only the doubling splits settle (not used by the Boolean cover check)
    for line in open(os.path.join(HERE, 'extra.txt')):
        t = tuple(int(x) for x in line.split())
        if t not in out:
            out.append(t)
    return sorted(out)


def load():
    cache = {}
    path = os.path.join(HERE, 'witnesses.txt')
    if os.path.exists(path):
        for line in open(path):
            N, u, v, l = line.split()
            cache[(int(N), int(u), int(v))] = [int(x) for x in l.split(',')]
    return cache


def main():
    os.chdir(HERE)
    cache = load()
    pairs = [t for t in core_pairs() if t[0] <= NMAX]
    for (N, u, v) in pairs:
        if (N, u, v) not in cache:
            seed = 1
            while True:
                l = witness(N, u, v, seed, 200000)
                if l:
                    break
                seed += 1
            cache[(N, u, v)] = l
            print('found', N, u, v, file=sys.stderr, flush=True)
        l = cache[(N, u, v)]
        assert sorted(l) == sorted(set(range(1, N + 1)) - {u, v}) and semi_ok(N, l)
    with open('witnesses.txt', 'w') as f:
        for k in sorted(cache):
            f.write('%d %d %d %s\n' % (k + (','.join(map(str, cache[k])),)))
    lines = ['-- BEGIN WITNESSES (generated by experiments/live7/gen_wit.py)', '']
    lines.append('/-- The hard core for `13 ≤ N ≤ %d` (`experiments/live6/core520.txt`, plus `extra.txt`: pairs settled only by doubling splits), `u ≤ N + 1 - v`. -/'
                 % NMAX)
    lines.append('def coreList : List (Nat × Nat × Nat) :=')
    lines.append('  [' + ', '.join('(%d, %d, %d)' % t for t in pairs) + ']')
    lines.append('')
    for (N, u, v) in pairs:
        lines.append('theorem wit_%d_%d_%d : witB %d %d %d' % (N, u, v, N, u, v))
        lines.append('    [' + ', '.join(map(str, cache[(N, u, v)])) + '] = true := by')
        lines.append('  decide +kernel')
        lines.append('')
    lines.append('theorem coReach_coreList {N u v : Nat} (h : (N, u, v) ∈ coreList) : CoReach N {u, v} := by')
    lines.append('  simp only [coreList, List.mem_cons, Prod.mk.injEq, List.not_mem_nil, or_false] at h')
    lines.append('  rcases h with ' + ' | '.join(['⟨rfl, rfl, rfl⟩'] * len(pairs)))
    for (N, u, v) in pairs:
        lines.append('  · exact coReach_of_witB wit_%d_%d_%d' % (N, u, v))
    lines.append('')
    lines.append('-- END WITNESSES')
    block = '\n'.join(lines)
    lean = os.path.join(HERE, '..', '..', 'Folds', 'Live7.lean')
    src = open(lean).read()
    a = src.index('-- BEGIN WITNESSES')
    b = src.index('-- END WITNESSES') + len('-- END WITNESSES')
    open(lean, 'w').write(src[:a] + block + src[b:])


if __name__ == '__main__':
    main()
