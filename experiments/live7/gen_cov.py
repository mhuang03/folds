"""gen_cov.py N1 N2: the Lean block of Folds/Live7.lean between '-- BEGIN COVER' and '-- END COVER':
one `decide` per N for `coverB N = true` (13 <= N <= N2), and their combination."""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
N1, N2 = int(sys.argv[1]), int(sys.argv[2])
lines = ['-- BEGIN COVER (generated by experiments/live7/gen_cov.py)', '']
for N in range(N1, N2 + 1):
    lines.append('theorem coverB_%d : coverB %d = true := by decide +kernel' % (N, N))
lines.append('')
lines.append('/-- The covering statement holds for `%d ≤ N ≤ %d` (verified search). -/' % (N1, N2))
lines.append('theorem coverB_small : ∀ N, %d ≤ N → N ≤ %d → coverB N = true := by' % (N1, N2))
lines.append('  intro N h1 h2')
lines.append('  interval_cases N')
for N in range(N1, N2 + 1):
    lines.append('  · exact coverB_%d' % N)
lines.append('')
lines.append('-- END COVER')
block = '\n'.join(lines)
lean = os.path.join(HERE, '..', '..', 'Folds', 'Live7.lean')
src = open(lean).read()
a = src.index('-- BEGIN COVER')
b = src.index('-- END COVER') + len('-- END COVER')
open(lean, 'w').write(src[:a] + block + src[b:])
