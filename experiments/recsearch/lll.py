"""Family 1b: lattice reduction for P-recursive relations beyond the exact range.

For (r, d) with K = (r+1)(d+1) unknowns > E = L - r equations there is always a
rational kernel, but its integer vectors are astronomically large for "random" data.
A genuine recurrence would be a kernel vector of small height.

Embedding: lattice generated by the K rows (e_i | W * M^T_i), i.e. all vectors
(c, W*M c), c in Z^K.  LLL gives |b1| <= 2^((K-1)/2) * lambda_1.  If some c* with
M c* = 0 has |c*| < W / 2^((K-1)/2), then b1 has norm < W, so its second block is 0 and
b1 = (c, 0) is itself a relation with |c| <= 2^((K-1)/2) |c*|.  Hence, rigorously,
  min{|c| : M c = 0, c != 0}  >=  B := |b1| / 2^((K-1)/2)    if b1 is a relation,
                              >=  W / 2^((K-1)/2)           otherwise.
We report log10 B for every box.  Positive control: a planted order-4, degree-3
recurrence with coefficients in [-3, 3] and n!-type growth (its relation has norm ~ 10).
Negative control: a(N) times random factors in [0.9,1.1] (same sizes, surely no relation): the size of
b1 in underdetermined boxes is the 'random' baseline to compare a(N) with.
"""
import math
import random
import sys
import flint
from common import A, NMAX

W = 10 ** 60


def rec_matrix(s, r, d, L):
    return [[n ** j * s[n - i] for i in range(r + 1) for j in range(d + 1)]
            for n in range(r + 1, L + 1)]


def log10_int(x):
    x = abs(int(x))
    if x == 0:
        return float('-inf')
    b = x.bit_length()
    if b > 1000:
        return math.log10(x >> (b - 60)) + (b - 60) * math.log10(2)
    return math.log10(x)


def embed_lll(rows):
    E = len(rows); K = len(rows[0])
    ent = []
    for i in range(K):
        ent += [1 if j == i else 0 for j in range(K)] + [W * rows[e][i] for e in range(E)]
    Lm = flint.fmpz_mat(K, K + E, ent).lll()
    b1 = [int(Lm[0, j]) for j in range(K + E)]
    is_rel = all(x == 0 for x in b1[K:])
    nrm2 = sum(x * x for x in b1[:K]) if is_rel else None
    return is_rel, b1[:K], nrm2


def planted(L=37):
    random.seed(7)
    p = [[random.randint(-3, 3) for _ in range(4)] for _ in range(3)]
    s = [None, 1, 2, 4, 10]
    for n in range(5, L + 1):
        v = n * s[n - 1]
        for t in range(3):
            v += sum(p[t][j] * n ** j for j in range(4)) * s[n - 2 - t]
        s.append(v)
    return s


def run(name, s, L, boxes, out):
    print(f'\n{name}', file=out)
    print('   r  d   K   E   b1 relation?  log10|b1|   log10 B (lower bound on norm of any relation)', file=out)
    for r, d in boxes:
        K = (r + 1) * (d + 1)
        E = L - r
        rows = rec_matrix(s, r, d, L)
        is_rel, v, nrm2 = embed_lll(rows)
        slack = (K - 1) / 2 * math.log10(2)
        if is_rel:
            lb = 0.5 * log10_int(nrm2) - slack
            line = f'  {r:2d} {d:2d} {K:3d} {E:3d}   yes          {0.5 * log10_int(nrm2):8.1f}   {lb:8.1f}'
            if 0.5 * log10_int(nrm2) < 6:
                line += f'   SMALL RELATION {v}'
        else:
            lb = math.log10(W) - slack
            line = f'  {r:2d} {d:2d} {K:3d} {E:3d}   no               -     {lb:8.1f}'
        print(line, file=out, flush=True)


def main():
    out = sys.stdout
    print(__doc__, file=out)
    L = NMAX
    boxes = []
    for r in range(1, 13):
        for d in range(0, 30):
            K = (r + 1) * (d + 1)
            if L - r - 5 < K <= 64:
                boxes.append((r, d))
    ctrl_boxes = [(4, 3), (4, 5), (5, 5), (6, 4), (4, 7), (7, 4)]
    run('control: planted order-4 degree-3 recurrence (true box K = 20)', planted(), L, ctrl_boxes, out)
    run('a(N), N <= 37', A, L, boxes, out)
    random.seed(11)
    for eps in (100, 10):     # relative noise 10% and 1% (in units of 1/1000)
        pert = [None] + [A[n] if n < 8 else A[n] * random.randint(1000 - eps, 1000 + eps) // 1000
                         for n in range(1, L + 1)]
        run(f'negative control: a(N) times a random factor in [1-{eps / 1000}, 1+{eps / 1000}] for N >= 8 (no relation expected)',
            pert, L, [b for b in boxes if (b[0] + 1) * (b[1] + 1) > L - b[0]], out)


if __name__ == '__main__':
    main()
