"""Generate the kernel-checked search certificates of Folds/Labelling.lean.
For each instance (left, N, t) the search tree (same semantics as `stepOK`/`extend` in Lean:
optimistic window inequality, checked at every k with m <= k <= m + r(m)) is cut into
subtrees of at most T nodes.  A small subtree becomes a theorem `Dead left N t q` proved by
`decide +kernel`; a big one is split into its children with `dead_of_children`.
Splitting keeps the kernel memory per declaration small (about 30 KB per node).
usage: gen_lean_checks.py T > snippet.lean"""
import sys
T = int(sys.argv[1]) if len(sys.argv) > 1 else 4000

def make(N, t, left):
    def r(m): return min(m - 1, N - m)
    def chk(m): return r(m) > 0 and (not left or 2 * m <= N + 1)
    def ok(c):
        k = len(c)
        for m in range(1, k + 1):
            if not (k <= m + r(m) and chk(m)): continue
            v = c[m - 1]; R = r(m)
            lhs = sum(c[x - 1] <= v for x in range(m - R, m))
            rhs = sum(1 if x > k else c[x - 1] < v for x in range(m + 1, m + R + 1))
            if lhs > rhs: return False
        return True
    size = {}
    def sz(q):
        # nodes of levelsFrom [q]: q itself plus all surviving extensions up to length N
        if len(q) == N: return 1
        s = 1
        for v in range(t):
            if ok(q + [v]): s += sz(q + [v])
        size[tuple(q)] = s
        return s
    total = sz([])
    return ok, size, total

out = []
def name(left, N, q):
    return f'dead{"L" if left else "F"}{N}_' + (''.join(map(str, q)) if q else 'root')

def emit(left, N, t):
    ok, size, total = make(N, t, left)
    stats = {'leaf': 0, 'split': 0}
    def go(q):
        nm = name(left, N, q)
        s = size.get(tuple(q), 1)
        lst = '[' + ', '.join(map(str, q)) + ']'
        L = 'true' if left else 'false'
        if s <= T or len(q) == N:
            stats['leaf'] += 1
            out.append(f'set_option maxRecDepth 100000 in\ntheorem {nm} : Dead {L} {N} {t} {lst} := by decide +kernel\n')
            return
        stats['split'] += 1
        kids = []
        for v in range(t):
            if ok(q + [v]):
                go(q + [v]); kids.append(f'Or.inr {name(left, N, q + [v])}')
            else:
                kids.append('Or.inl (by decide +kernel)')
        alts = ' | '.join(['rfl'] * t)
        cases = ' ∨ '.join(f'v = {v}' for v in range(t))
        body = f'theorem {nm} : Dead {L} {N} {t} {lst} :=\n  dead_of_children {lst} (by decide) (by\n    intro v hv\n    rcases (show {cases} by omega) with {alts}\n'
        for k in kids:
            body += f'    · exact {k}\n'
        body += '    )\n'
        out.append(body)
    go([])
    return total, stats

info = []
for (left, N, t) in [(True, 3, 1), (True, 9, 2), (False, 7, 2), (False, 8, 2), (True, 21, 3)] + \
                     [(False, N, 3) for N in range(15, 21)]:
    total, stats = emit(left, N, t)
    info.append(f'-- {"left-half-only" if left else "full"} N = {N}, t = {t}: {total} prefixes, '
                f'{stats["leaf"]} kernel leaves, {stats["split"]} splits')
print('/-! ### Generated by experiments/labelling2/gen_lean_checks.py (T = %d)\n%s\n-/\n' % (T, '\n'.join(i[3:] for i in info)))
print('\n'.join(out))
