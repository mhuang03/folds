"""gen_cov8.py N1 N2: write the certificate block of Folds/Live8.lean (between the markers
'-- BEGIN CERTS' and '-- END CERTS'): one `mixedB_N` theorem per N (certificates from gencert),
and `mixedCover_le` collecting them by `interval_cases`."""
import os
import subprocess
import sys

here = os.path.dirname(os.path.abspath(__file__))
root = os.path.abspath(os.path.join(here, '..', '..'))
N1, N2 = int(sys.argv[1]), int(sys.argv[2])
body = subprocess.run([os.path.join(here, 'gencert'), str(N1), str(N2)], capture_output=True,
                      text=True, check=True).stdout
lines = ['-- BEGIN CERTS (generated by experiments/live8/gen_cov8.py)', '', body.rstrip(), '']
lines.append('/-- The mixed-parity covering statement for `%d ≤ N ≤ %d` (verified certificates). -/' % (N1, N2))
lines.append('theorem mixedCover_le : ∀ N, %d ≤ N → N ≤ %d → MixedCover N := by' % (N1, N2))
lines.append('  intro N h1 h2')
lines.append('  interval_cases N')
for N in range(N1, N2 + 1):
    lines.append('  · exact mixedCover_of_B mixedB_%d' % N)
lines.append('')
lines.append('-- END CERTS')
block = '\n'.join(lines)
p = os.path.join(root, 'Folds', 'Live8.lean')
s = open(p).read()
a = s.index('-- BEGIN CERTS')
b = s.index('-- END CERTS') + len('-- END CERTS')
s = s[:a] + block + s[b:]
open(p, 'w').write(s)
print('wrote', len(block), 'bytes')
