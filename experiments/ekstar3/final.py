# final.py M > ../../Folds/EkStar3.lean : core.lean + the certificates for N <= M (mkE.py, from
# bin/hE/<N>.txt) + the final theorems.
import sys, io
import mkE

M = int(sys.argv[1])
out = sys.stdout
out.write(open('core.lean').read().rstrip() + '\n\n')
out.write('/-! ## Certificates for `N ≤ %d` (generated by `experiments/ekstar3/mkE.py`)\n\n' % M)
out.write('Checked sequentially (`Elab.async false`) to keep the memory low. -/\n\n')
out.write('set_option Elab.async false\n\n')
for N in range(0, M + 1):
    mkE.gen(N, 40, out)
covs = ', '.join('e3_of_covE IH hG cove_%d' % N for N in range(0, M + 1))
out.write('''/-! ## E*_3 for `N ≤ %(M)d`, and for all `N` modulo the residual -/

/-- **E*_3 for every `N ≤ %(M)d`**: every 3-subset `{a, b, c}` of `[2, N - 1]` is co-reachable. -/
theorem e3_le_%(M)d : ∀ N, N ≤ %(M)d → E3 N := by
  intro N
  induction N using Nat.strong_induction_on with
  | _ N ih =>
    intro hN
    have IH : ∀ q, q < N → E3 q := fun q hq => ih q hq (by omega)
    have hG : N ≠ 7 → Good3 N := fun h7 => good3_le_50 N (by omega) h7
    interval_cases N
    exacts [%(covs)s]

/-- **E*_3 for every `N ≤ %(M)d`**, set form. -/
theorem ekStar_three_le_%(M)d {N : Nat} (hN : N ≤ %(M)d) {D : Finset Nat}
    (hD : D ⊆ Finset.Icc 2 (N - 1)) (hc : D.card = 3) : CoReach N D :=
  coReach_of_e3 (e3_le_%(M)d N hN) hD hc

/-- **E*_3 for all `N`, modulo the residual**: if for every `N > %(M)d` the interior triples not
settled by `CoveredES` are co-reachable, then every 3-subset of `[2, N - 1]` is co-reachable
for every `N`, i.e. Conjecture E*_3 (`EkStar.EkStarConj 3`) holds. -/
theorem ekStar_three_of_residual (hres : ∀ N, %(M)d < N → ResidualE N) :
    EkStar.EkStarConj 3 :=
  ekStarConj_three_of (e3_of_residualE e3_le_%(M)d hres)

end EkStar3
end Folds
''' % {'M': M, 'covs': covs})
