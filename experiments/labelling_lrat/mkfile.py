"""Write a Lean file of LRAT certificates (see gen.py).

usage: mkfile.py OUT.lean MODULE_DOC t SPEC...
  SPEC = N (full problem at N) or LK (left-half-only problem at K), e.g. L21 15 16 17
Each SPEC gives `def cert_F{N}_{t} : Cert` / `cert_L{K}_{t}` and the theorem
`noLab_F{N}_{t} : NoLab false N t` / `noLab_L{K}_{t} : NoLab true K t`, checked by `decide +kernel`.
"""
import os, sys, tempfile
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import gen

out, doc, t = sys.argv[1], sys.argv[2], int(sys.argv[3])
specs = sys.argv[4:]
parts = ['import Folds.LabellingSAT\n',
         f'/-!\n# {doc}\n\nGenerated by `experiments/labelling_lrat/mkfile.py` (do not edit): LRAT\n'
         'certificates from CaDiCaL, trimmed by lrat-trim, checked by the kernel\n'
         '(`Folds.LSAT.Cert.sound`, `decide +kernel`).\n-/\n',
         'namespace Folds.LSAT\n']
for sp in specs:
    left = sp.startswith('L')
    N = int(sp[1:] if left else sp)
    tag = f'{"L" if left else "F"}{N}_{t}'
    with tempfile.TemporaryDirectory() as tmp:
        vt, init, stp, nvars, ncls = gen.solve(N, t, left, tmp)
    sys.stderr.write(f'{tag}: {nvars} vars {ncls} clauses -> used {len(init)} clauses, '
                     f'{len(vt) - 1} vars, {len(stp)} steps, {sum(len(h) for _, h in stp)} hints\n')
    parts.append(gen.emit(f'cert_{tag}', vt, init, stp))
    parts.append(f'theorem noLab_{tag} : NoLab {"true" if left else "false"} {N} {t} :=\n'
                 f'  Cert.sound cert_{tag} (by decide +kernel)\n')
parts.append('end Folds.LSAT\n')
with open(out, 'w') as f:
    f.write('\n'.join(parts))
