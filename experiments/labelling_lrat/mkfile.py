"""Write a Lean file of LRAT certificates (see gen.py).

usage: mkfile.py OUT.lean MODULE_DOC t SPEC...
  SPEC = N (full problem at N) or LK (left-half-only problem at K), e.g. L21 15 16 17
Each SPEC gives `def cert_F{N}_{t} : Cert` / `cert_L{K}_{t}` with its Boolean checks
(`decide +kernel`): `_init`, the proof steps in segments of about LSAT_HINTS (env, default 6000)
hints, one declaration each (memory of the kernel), and `_end`.  The certificate file imports
only Folds.LabellingSATCore (no Mathlib).  With --nolab=FILE, the text of the theorems
`noLab_F{N}_{t} : NoLab false N t` / `noLab_L{K}_{t} : NoLab true K t` (assembled from the
checks by Folds.LSAT.Cert.sound_of_refutes) is written to FILE, to be pasted into a file that
imports Folds.LabellingSAT.
"""
import os, sys, tempfile
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import gen

out, doc, t = sys.argv[1], sys.argv[2], int(sys.argv[3])
specs = [a for a in sys.argv[4:] if not a.startswith('--')]
noLabOut = next((a[len('--nolab='):] for a in sys.argv if a.startswith('--nolab=')), None)
noLab = []
BUDGET = int(os.environ.get('LSAT_HINTS', '6000'))
parts = ['import Folds.LabellingSATCore\n',
         f'/-!\n# {doc}\n\nGenerated by `experiments/labelling_lrat/mkfile.py` (do not edit): LRAT\n'
         'certificates from CaDiCaL, trimmed by lrat-trim, checked by the kernel\n'
         '(`decide +kernel`; soundness: `Folds.LSAT.Cert.sound_of_refutes`), in segments of about\n'
         f'{BUDGET} hints per declaration to bound the memory of the kernel.\n-/\n',
         '-- one kernel check at a time (memory)\nset_option Elab.async false\n',
         'namespace Folds.LSAT\n']
for sp in specs:
    left = sp.startswith('L')
    N = int(sp[1:] if left else sp)
    lb = 'true' if left else 'false'
    tag = f'{"L" if left else "F"}{N}_{t}'
    with tempfile.TemporaryDirectory() as tmp:
        vt, init, stp, nvars, ncls = gen.solve(N, t, left, tmp)
    sys.stderr.write(f'{tag}: {nvars} vars {ncls} clauses -> used {len(init)} clauses, '
                     f'{len(vt) - 1} vars, {len(stp)} steps, {sum(len(h) for _, h in stp)} hints\n')
    c = f'cert_{tag}'
    parts.append(gen.emit_str(c, vt, init, stp))
    parts.append(f'theorem {c}_init : {c}.initOK {lb} {N} {t} = true := by\n  decide +kernel\n')
    bounds, acc = [0], 0
    for k, (_, h) in enumerate(stp):
        if acc and acc + len(h) > BUDGET:
            bounds.append(k)
            acc = 0
        acc += len(h)
    bounds.append(len(stp))
    for a, b in zip(bounds, bounds[1:]):
        parts.append(f'theorem {c}_{a} : {c}.segOK {a} {b} = true := by decide +kernel\n')
    parts.append(f'theorem {c}_end : {c}.endOK {len(stp)} = true := by decide +kernel\n')
    ch = ''.join(f'\n    {c}.refutes_seg {c}_{a} <|' for a in bounds[:-1])
    noLab.append(f'theorem noLab_{tag} : NoLab {lb} {N} {t} :=\n'
                 f'  {c}.sound_of_refutes {c}_init <|{ch}\n    {c}.refutes_end {c}_end\n')
parts.append('end Folds.LSAT\n')
with open(out, 'w') as f:
    f.write('\n'.join(parts))
if noLabOut:
    with open(noLabOut, 'w') as f:
        f.write('\n'.join(noLab))
