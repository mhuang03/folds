"""genall.py: Lean generation for ThinCover from the saved designs (tmp/designs*.pkl).

  python3 genall.py lines     -> Folds/ThinCoverDiag.lean, Folds/ThinCoverStrip{A,B,C}.lean, Folds/ThinCoverShapes.lean
  python3 genall.py cluster   -> Folds/ThinCoverCluster*.lean

Each leaf piece is re-certified (LP results cached in tmp/lpcache.pkl) and printed by gen.Piece.lean;
the tree of splits of a line is printed as one lemma per line (case split by `le_total`)."""
import os
import sys
import sympy as sp
from gen import nat_ineq, lean_nat, save_cache
import pieces as PC

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', 'Folds')
HEADER = '''import Folds.ThinCoverBase

/-! Generated by `experiments/thincover/genall.py` (see `experiments/thincover/PROOFS.txt`). -/

set_option linter.unusedTactic false
set_option linter.unreachableTactic false
set_option linter.unusedVariables false
set_option linter.style.longLine false
set_option maxHeartbeats 1000000

namespace Folds
namespace ThinCover

open Residual CoverAll

'''
FOOTER = '\nend ThinCover\nend Folds\n'


def leaf(pc, c0, act):
    pc.c0, pc.act = c0, act
    res = pc.certify(verbose=True)
    if not res[0]:
        raise RuntimeError('certificate failed: ' + pc.name)
    return pc.lean(res)


def tree_lemma(name, base, hyps, vars_, concl, tree, doc):
    """lemma `name` (hypotheses `hyps`) from the leaves of `tree` = Piece | (form, ge, le)."""
    V = vars_
    hs = ' '.join('(h%d : %s)' % (i, nat_ineq(h, V)) for i, h in enumerate(hyps))
    out = ['/-- %s -/' % doc, 'theorem %s {%s : ℕ} %s :\n    %s := by' % (name, ' '.join(map(str, V)), hs, concl)]

    def rec(t, ind):
        pad = '  ' * ind
        if isinstance(t, tuple):
            f, a, b = t
            f = sp.expand(f)
            pos = sum((x for x in sp.Add.make_args(f) if x.as_coeff_Mul()[0] > 0), sp.Integer(0))
            neg = -sum((x for x in sp.Add.make_args(f) if x.as_coeff_Mul()[0] < 0), sp.Integer(0))
            ln = lambda e: lean_nat(e, V) if e != 0 else '0'  # noqa: E731
            out.append('%srcases le_total (%s) (%s) with _ | _' % (pad, ln(neg), ln(pos)))
            out.append('%s· ' % pad)
            rec(a, ind + 1)
            out.append('%s· ' % pad)
            rec(b, ind + 1)
        else:
            args = ' '.join('(by omega)' for _ in t.hyps)
            out.append('%sexact %s %s' % (pad, t.name, args))
    rec(tree, 1)
    # merge "· " lines with the following line
    txt = '\n'.join(out)
    import re
    txt = re.sub(r'· \n\s+', '· ', txt)
    return txt + '\n'


def build_tree(key, mk, splitter, designs, tag=''):
    k = (key, tag)
    if k in designs:
        val = designs[k]
        extra, c0, act = val[:3]
        pc = mk(extra, tag) if len(val) == 3 else mk(extra, tag, val[3])
        pc.c0, pc.act = c0, act
        return pc
    f = splitter(tag)
    return (f, build_tree(key, mk, splitter, designs, tag + 'a'), build_tree(key, mk, splitter, designs, tag + 'b'))


def leaves(t):
    if isinstance(t, tuple):
        return leaves(t[1]) + leaves(t[2])
    return [t]


N, u, w = PC.N, PC.u, PC.w


def strip_splitter(e):
    a, b = PC.strip_shift(e)
    U = w + a
    sp_ = {'': 2 * N - 13 * U, 'a': 4 * N - 29 * U, 'b': 4 * N - 23 * U,
           'aa': 8 * N - 61 * U, 'ab': 8 * N - 55 * U, 'ba': 8 * N - 49 * U, 'bb': 8 * N - 43 * U}
    return lambda t: sp_.get(t)


def gen_lines():
    D = PC.all_designs()
    files = {'Diag': [], 'StripA': [], 'StripB': [], 'StripC': [], 'Shapes': []}
    # diagonal lines
    for d, (code, umin) in sorted(PC.DIAG.items()):
        t = build_tree(('diag', d), lambda extra, tag, d=d, umin=umin: PC.diag_piece(d, umin, extra=extra, tag=tag),
                       lambda tag: None, D)
        for lf in leaves(t):
            files['Diag'].append(leaf(lf, lf.c0, lf.act))
        save_cache()
    # d = 1 corner and shapes
    for nm in ['d1corner'] + ['shape_%d_%d' % (a, b) for a, b, c in PC.SHAPES] + ['shape_3_9', 'shape_3_10'] + \
            ['sshape_%d_%d' % (us, 2 * us + e) for e, us in PC.SSHAPES]:
        extra, c0, act = D[(nm, '')][:3]
        pc = PC.PIECES[nm]()
        files['Shapes' if nm != 'd1corner' else 'Diag'].append(leaf(pc, c0, act))
        save_cache()
    # strip lines
    for e in sorted(PC.STRIP):
        a, b = PC.strip_shift(e)

        def mk(extra, tag, code=None, e=e):
            return PC.strip_piece(e, extra=extra, tag=tag, code=code)
        t = build_tree(('strip', e), mk, strip_splitter(e), D)
        fk = 'StripA' if e < -2 else ('StripB' if e < 6 else 'StripC')
        for lf in leaves(t):
            files[fk].append(leaf(lf, lf.c0, lf.act))
        if isinstance(t, tuple):
            base = PC.strip_piece(e)
            nm = 'strip%s' % (('m%d' % -e) if e < 0 else str(e))
            files[fk].append(tree_lemma(nm, base, base.hyps, base.vars,
                                        'RegionSL N (%s) (%s)' % (lean_nat(w + a, [N, w]), lean_nat(2 * w + b, [N, w])),
                                        t, "The line `u' = 2u %s %d` of the strip (all pieces)." % ('-' if e < 0 else '+', abs(e))))
        save_cache()
    for k, parts in files.items():
        open(os.path.join(ROOT, 'ThinCover%s.lean' % k), 'w').write(HEADER + '\n'.join(parts) + FOOTER)
        print('wrote', k, len(parts))


if __name__ == '__main__':
    if sys.argv[1] == 'lines':
        gen_lines()
