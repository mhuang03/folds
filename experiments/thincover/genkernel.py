"""genkernel.py: the kernel checks of the cluster box for 301 <= N < 1000 (Folds/ThinCoverKernel*.lean):
one theorem `clCheck N = true := by decide +kernel` per N (kernel evaluation, no native code),
25 per file, and the lemma `clCheck_small : 301 ≤ N → N < 1000 → clCheck N = true`.
Each file elaborates within `lean -M 3000` (2-7 s per N).
python3 genkernel.py [asm]   (asm: only the aggregating file Folds/ThinCoverKernel.lean)"""
import os
import sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', 'Folds')
LO, HI, PER = 301, 1000, 25
HDR = '''import Folds.ThinCoverKernelDefs

/-! Generated by `experiments/thincover/genkernel.py`: kernel checks `clCheck N = true` of the cluster
box (`experiments/thincover/PROOFS.txt`). -/

namespace Folds
namespace ThinCover

'''
FTR = '\nend ThinCover\nend Folds\n'


def main(asm_only=False):
    Ns = list(range(LO, HI))
    files = []
    for k in range(0, len(Ns), PER):
        fn = 'ThinCoverKernel%02d' % (k // PER + 1)
        if not asm_only:
            body = ''.join('theorem clCheck_%d : clCheck %d = true := by decide +kernel\n' % (n, n)
                           for n in Ns[k:k + PER])
            open(os.path.join(ROOT, fn + '.lean'), 'w').write(HDR + body + FTR)
        files.append(fn)
    L = [''.join('import Folds.%s\n' % f for f in files),
         '\n/-! The cluster checks for all `301 ≤ N < 1000` (`genkernel.py`). -/\n\n'
         'namespace Folds\nnamespace ThinCover\n\n']
    for k in range(0, len(Ns), PER):
        blk = Ns[k:k + PER]
        a, b = blk[0], blk[-1] + 1
        L.append('theorem clCheck_block_%d {N : ℕ} (h1 : %d ≤ N) (h2 : N < %d) : clCheck N = true := by\n' % (a, a, b))
        L.append('  interval_cases N\n')
        for n in blk:
            L.append('  · exact clCheck_%d\n' % n)
        L.append('\n')
    L.append('theorem clCheck_small {N : ℕ} (h1 : 301 ≤ N) (h2 : N < 1000) : clCheck N = true := by\n')
    for k in range(0, len(Ns), PER):
        blk = Ns[k:k + PER]
        a, b = blk[0], blk[-1] + 1
        L.append('  by_cases hb%d : N < %d\n  · exact clCheck_block_%d (by omega) hb%d\n' % (a, b, a, a))
    L.append('  omega\n')
    L.append(FTR)
    open(os.path.join(ROOT, 'ThinCoverKernel.lean'), 'w').write(''.join(L))
    print(len(files), 'files')


if __name__ == '__main__':
    main(len(sys.argv) > 1 and sys.argv[1] == 'asm')
