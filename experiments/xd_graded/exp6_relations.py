"""Experiment 6: other operator relations for U and D = U^T (unweighted).

Usage: python3 exp6_relations.py NMAX [kinds]

For each N, vertex set and rank k (exact integer arithmetic via python-flint):
 (a) q-commutation: is D U in span{U D, I} on V_k?   (DU = q_k UD + r_k I, Lam / Fomin)
 (b) do DU and UD commute on V_k?                       (true whenever (a) holds)
 (c) down-up algebra (Benkart-Roby): is D^2 U in span{D U D, U D^2, D} as maps V_k -> V_{k-1}?
     and is U^2 D ... (the transposed relation is equivalent since D = U^T)
 (d) is the commutator C_k = DU - UD in the algebra generated by the diagonal matrices
     diag(up), diag(down) and I?  (i.e. is it diagonal?)  -> number of off-diagonal nonzeros.
A relation is reported as 'holds' only if the corresponding matrices are linearly dependent
with a nonzero coefficient on the leading term.
"""
import sys
from collections import Counter
import flint
from common import vertex_sets, up_edges


def fm(rows, cols, entries):
    M = [[0] * cols for _ in range(rows)]
    for (i, j), v in entries.items():
        M[i][j] = v
    return flint.fmpz_mat(M)


def vec(M):
    return [int(M[i, j]) for i in range(M.nrows()) for j in range(M.ncols())]


def in_span(target, others):
    """Is target in the Q-span of others (all flint matrices of equal shape)?"""
    cols = [vec(M) for M in others] + [vec(target)]
    A = flint.fmpz_mat([list(r) for r in zip(*cols)])  # rows = coordinates
    r_all = A.rank()
    B = flint.fmpz_mat([list(r) for r in zip(*cols[:-1])]) if others else None
    r_oth = B.rank() if B is not None else 0
    return r_all == r_oth


def main():
    NMAX = int(sys.argv[1])
    kinds = sys.argv[2].split(',') if len(sys.argv) > 2 else ['all', 'live']
    for N in range(2, NMAX + 1):
        for kind in kinds:
            lev, g, pc = vertex_sets(N, kind)
            E = up_edges(N, lev, pc)
            sizes = [len(l) for l in lev]
            U = []
            for k in range(N):
                ent = Counter()
                for i, j, _ in E[k]:
                    ent[(j, i)] += 1
                U.append(fm(sizes[k + 1], sizes[k], ent))
            D = [None] + [U[k].transpose() for k in range(N)]   # D[k] : V_k -> V_{k-1}
            qa, cb, du = [], [], []
            for k in range(1, N):
                DU = D[k + 1] * U[k]
                UD = U[k - 1] * D[k]
                I = fm(sizes[k], sizes[k], {(i, i): 1 for i in range(sizes[k])})
                qa.append(in_span(DU, [UD, I]))
                comm = DU * UD - UD * DU
                cb.append(all(x == 0 for x in vec(comm)))
                if k >= 2:
                    D2U = D[k] * D[k + 1] * U[k]
                    DUD = D[k] * U[k - 1] * D[k]
                    UD2 = U[k - 2] * D[k - 1] * D[k]
                    du.append(in_span(D2U, [DUD, UD2, D[k]]))
                else:
                    D2U = D[k] * D[k + 1] * U[k]
                    DUD = D[k] * U[k - 1] * D[k]
                    du.append(in_span(D2U, [DUD, D[k]]))
            f = lambda L: ''.join('Y' if x else 'n' for x in L)
            print(f"N={N} {kind}: sizes={sizes}")
            print(f"   ranks k=1..N-1:  DU in span(UD, I): {f(qa)}   [DU, UD] = 0: {f(cb)}"
                  f"   D^2U in span(DUD, UD^2, D): {f(du)}")
            sys.stdout.flush()


if __name__ == '__main__':
    main()
